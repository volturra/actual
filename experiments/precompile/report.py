#!/usr/bin/env python3
"""Turn results/raw.json (+ logs/compile.tsv) into results/tables.md."""
import json, os, statistics

HERE = os.path.dirname(os.path.abspath(__file__))
data = json.load(open(os.path.join(HERE, "results", "raw.json")))
rows = data["results"]
configs = list(dict.fromkeys(r["config"] for r in rows))
workloads = list(dict.fromkeys(r["workload"] for r in rows))
idx = {(r["workload"], r["mode"], r["config"]): r for r in rows}


def cell(wl, mode, cfg, key, base_key=None, fmt="{:.0f}"):
    r = idx.get((wl, mode, cfg))
    if not r or "error" in r:
        return "fail"
    v = r.get(key)
    if v is None:
        return "n/a"
    s = fmt.format(v)
    node = idx.get((wl, mode, "node"))
    if base_key and node and "error" not in node and node.get(key):
        s += f" ({v / node[key]:.2f}x)"
    if mode == "run" and node and "error" not in node and r["checksum"] != node["checksum"]:
        s += " **≠**"
    return s


def table(title, mode, key, note, rel=True, fmt="{:.0f}"):
    out = [f"### {title}", "", note, "", "| workload | " + " | ".join(configs) + " |", "|---" * (len(configs) + 1) + "|"]
    for wl in workloads:
        out.append(f"| {wl} | " + " | ".join(cell(wl, mode, c, key, key if rel else None, fmt) for c in configs) + " |")
    return "\n".join(out) + "\n"


def common_set():
    # Same workloads for every config: the GC probe is not Actual code, and a
    # workload any engine gets wrong (or fails) is left out for all of them.
    keep = []
    for wl in workloads:
        if wl == "gc":
            continue
        node = idx[(wl, "run", "node")]
        if all((wl, "run", c) in idx and "error" not in idx[(wl, "run", c)] and idx[(wl, "run", c)]["checksum"] == node["checksum"] for c in configs):
            keep.append(wl)
    return keep


COMMON = common_set()


def geomean_row(mode, key):
    out = []
    for c in configs:
        ratios = [idx[(wl, mode, c)][key] / idx[(wl, mode, "node")][key] for wl in COMMON]
        out.append(f"{statistics.geometric_mean(ratios):.2f}x")
    return f"| geomean vs node ({', '.join(COMMON)}) | " + " | ".join(out) + " |"


md = ["# Precompile benchmark tables", "", "Generated by report.py from results/raw.json.",
      f"Host: {data['meta']['cpu']}, {data['meta']['nproc']} vCPU, pinned to {data['meta']['pin'][-1]}. "
      f"Load average at start {data['meta']['loadavg_start'][0]:.2f}, end {data['meta']['loadavg_end'][0]:.2f}.",
      "Lower is better everywhere. Ratios are against `node`. **≠** marks a checksum that differs from Node's (wrong result).", ""]
md.append(table("Steady-state time per iteration (ms)", "run", "steady_median",
                "Median of in-process iterations 2..N across processes. This is how fast the code runs once loaded and warmed up."))
md[-1] = md[-1].rstrip("\n") + "\n" + geomean_row("run", "steady_median") + "\n"
md.append(table("Cold first iteration (ms)", "run", "cold_median",
                "First in-process iteration: includes lazy compilation and JIT tier-up, but not process start."))
md[-1] = md[-1].rstrip("\n") + "\n" + geomean_row("run", "cold_median") + "\n"
md.append(table("Startup: process wall time with no work (ms)", "n0", "wall_median",
                "Wall clock for the N=0 bundle: process start, runtime init, loading/parsing the bundle, module init. "
                f"Launching `/bin/true` the same way takes {data['meta'].get('true_wall_ms', float('nan')):.1f} ms, so cells near that are pure process cost and can't be ranked against each other. "
                "The `hermes` column is the CLI's default eager compile; see the lazy column below."))
if any("lazy_wall_median" in r for r in rows):
    md += ["| workload | hermes (eager, default) | hermes -lazy | hermes-hbc |", "|---|---|---|---|"]
    for wl in workloads:
        h = idx[(wl, "n0", "hermes")]; b = idx[(wl, "n0", "hermes-hbc")]
        md.append(f"| {wl} | {h['wall_median']:.0f} | {h['lazy_wall_median']:.0f} | {b['wall_median']:.0f} |")
    md.append("")
for r in rows:
    if "maxrss_kib" in r:
        r["maxrss_mib"] = r["maxrss_kib"] / 1024
    if r.get("rss_kib"):
        r["rss_mib"] = r["rss_kib"] / 1024
    if "ship_bytes" in r:
        r["ship_mib"] = r["ship_bytes"] / 1048576
    if "ship_stripped_bytes" in r:
        r["ship_stripped_mib"] = r["ship_stripped_bytes"] / 1048576
md.append(table("Peak RSS, full run (MiB)", "run", "rss_mib",
                "Peak resident set size, measured through bin/rss (a tiny C launcher; `/bin/true` reads "
                f"{data['meta'].get('true_rss_kib', 0) / 1024:.1f} MiB). The bench.py `maxrss_kib` field is floored at the Python parent's RSS and is not used.", fmt="{:.1f}"))
md.append(table("Peak RSS, idle N=0 bundle (MiB)", "n0", "rss_mib",
                "Baseline cost of the runtime plus the loaded bundle; Node reserves a large part of its full-run number here.", fmt="{:.1f}"))
md.append(table("Size to ship, stripped (MiB)", "run", "ship_stripped_mib",
                "Runtime binary + bundle, or compiled artifact + the shared libraries it needs, after `strip`. "
                "libc, libm and libstdc++ (needed by hermes, shermes and porffor builds, not by QuickJS) are not counted.",
                rel=False, fmt="{:.1f}"))

tsv = os.path.join(HERE, "logs", "compile.tsv")
if os.path.exists(tsv):
    md += ["### Compile results", "", "| bundle | tool | exit | seconds |", "|---|---|---|---|"]
    last = {}
    for line in open(tsv):
        b, t, rc, s = line.rstrip("\n").split("\t")
        last[(b, t)] = (rc, s)  # a partial recompile appends; the last entry wins
    for (b, t), (rc, s) in sorted(last.items()):
        if b.endswith(".run"):
            md.append(f"| {b} | {t} | {rc} | {s} |")
    md.append("")

errs = [r for r in rows if "error" in r]
if errs:
    md += ["### Failures", ""] + [f"- {r['workload']}.{r['mode']} on {r['config']}: `{r['error'][:200].strip()}`".replace("\n", " ") for r in errs] + [""]
open(os.path.join(HERE, "results", "tables.md"), "w").write("\n".join(md))
print("\n".join(md))
